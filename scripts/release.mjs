import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const pkg = JSON.parse(await read('package.json'));
const sw = await read('sw.js');
const assets = JSON.parse(sw.match(/const ASSETS = (\[[\s\S]*?\]);/)[1].replaceAll("'", '"').replace(/,\s*]/g, ']'));
const hash = createHash('sha256');
hash.update(pkg.version);
for (const path of [...new Set(assets.filter(p => p !== './' && p !== './src/version.js'))].sort()) {
  hash.update(path); hash.update(await readFile(new URL(path, root)));
}
hash.update(sw.replace(/const CACHE = '[^']+';/, "const CACHE = '__RELEASE__';"));
const build = hash.digest('hex').slice(0, 12);
const id = `${pkg.version}+${build}`;
const version = `// Generated by npm run release.\nexport const VERSION = ${JSON.stringify(id)};\n`;
const updatedSW = sw.replace(/const CACHE = '[^']+';/, `const CACHE = 'toukan-${id}';`);
if (process.argv.includes('--check')) {
  if (await read('src/version.js') !== version || sw !== updatedSW) {
    throw new Error('Release assets changed. Run npm run release, then commit the generated files.');
  }
} else {
  await writeFile(new URL('src/version.js', root), version);
  await writeFile(new URL('sw.js', root), updatedSW);
}
console.log(`Release ${id}${process.argv.includes('--check') ? ' verified' : ' prepared'}`);
